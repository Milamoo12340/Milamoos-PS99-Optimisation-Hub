import { Optimization } from './optimizations';

export type ScriptFormat = 'powershell' | 'json' | 'ahk' | 'bat';

interface GeneratorOptions {
  format: ScriptFormat;
  selectedIds: Set<string>;
  optimizations: Optimization[];
}

/**
 * Collect all flags from selected optimizations into a flat record
 */
function collectFlags(selectedIds: Set<string>, optimizations: Optimization[]): Record<string, string | number | boolean> {
  const flags: Record<string, string | number | boolean> = {};
  for (const opt of optimizations) {
    if (selectedIds.has(opt.id)) {
      Object.assign(flags, opt.flags);
    }
  }
  return flags;
}

/**
 * Generate a PowerShell script that writes FFlags to the Roblox ClientSettings file
 */
export function generatePowershellScript(selectedIds: Set<string>, optimizations: Optimization[]): string {
  const flags = collectFlags(selectedIds, optimizations);
  const selectedOpts = optimizations.filter(o => selectedIds.has(o.id));
  
  const flagsJson = JSON.stringify(flags, null, 2);
  const names = selectedOpts.map(o => `#   - ${o.name} (${o.riskLevel} risk)`).join('\n');

  return `# ============================================================
# PS99 Performance Optimisation — Generated by Milamoo's Hub
# Applied optimisations:
${names}
# ============================================================
# Run as Administrator!

$ErrorActionPreference = "Stop"

function Assert-Admin {
  $isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
  if (-not $isAdmin) {
    Start-Process -FilePath pwsh -ArgumentList "-NoProfile -ExecutionPolicy Bypass -File \`"$PSCommandPath\`"" -Verb RunAs
    exit
  }
}

Assert-Admin

# Roblox ClientSettings path
$robloxPaths = @(
  "$env:LOCALAPPDATA\\Roblox\\Versions",
  "$env:PROGRAMFILES\\Roblox\\Versions",
  "$env:PROGRAMFILES(X86)\\Roblox\\Versions"
)

$settingsPath = $null
foreach ($base in $robloxPaths) {
  if (Test-Path $base) {
    $versions = Get-ChildItem -Path $base -Directory | Sort-Object LastWriteTime -Descending
    foreach ($ver in $versions) {
      $candidate = Join-Path $ver.FullName "ClientSettings\\ClientAppSettings.json"
      if (Test-Path (Split-Path $candidate)) {
        $settingsPath = $candidate
        break
      }
      # Create the ClientSettings folder if missing
      $csFolder = Join-Path $ver.FullName "ClientSettings"
      New-Item -ItemType Directory -Path $csFolder -Force | Out-Null
      $settingsPath = $candidate
      break
    }
    if ($settingsPath) { break }
  }
}

if (-not $settingsPath) {
  Write-Host "❌ Could not find Roblox installation. Is Roblox installed?" -ForegroundColor Red
  pause
  exit 1
}

Write-Host "📁 Target: $settingsPath" -ForegroundColor Cyan

# Load existing settings if present
$existing = @{}
if (Test-Path $settingsPath) {
  try {
    $existing = Get-Content $settingsPath -Raw | ConvertFrom-Json -AsHashtable
    Write-Host "✅ Loaded existing settings ($($existing.Count) flags)" -ForegroundColor Green
  } catch {
    Write-Host "⚠️ Could not parse existing file — starting fresh" -ForegroundColor Yellow
  }
}

# Apply new flags
$newFlags = ${flagsJson} | ConvertFrom-Json -AsHashtable
foreach ($key in $newFlags.Keys) {
  $existing[$key] = $newFlags[$key]
}

# Write back
$existing | ConvertTo-Json -Depth 5 | Set-Content -Path $settingsPath -Encoding UTF8
Write-Host "✅ Applied $($newFlags.Count) FFlags to $settingsPath" -ForegroundColor Green
Write-Host ""
Write-Host "🎮 Restart Roblox to apply changes!" -ForegroundColor Yellow
pause
`;
}

/**
 * Generate a raw JSON FFlag config — paste directly into ClientAppSettings.json
 */
export function generateJsonConfig(selectedIds: Set<string>, optimizations: Optimization[]): string {
  const flags = collectFlags(selectedIds, optimizations);
  return JSON.stringify(flags, null, 2);
}

/**
 * Generate a simple AutoHotkey v2 script that writes FFlags to ClientAppSettings.json
 * in the latest Roblox version folder.
 */
export function generateAHKScript(selectedIds: Set<string>, optimizations: Optimization[]): string {
  const flags = collectFlags(selectedIds, optimizations);
  const selectedOpts = optimizations.filter(o => selectedIds.has(o.id));
  const flagsJson = JSON.stringify(flags, null, 2);

  return `#Requires AutoHotkey v2.0
; ============================================================
; PS99 FFlag Optimiser — Generated by Milamoo's Hub
; Applied: ${selectedOpts.map(o => o.name).join(', ')}
; ============================================================

; Find the latest Roblox version folder
versionsPath := "C:\\Users\\" A_UserName "\\AppData\\Local\\Roblox\\Versions"
latestDir := ""
latestTime := 0

Loop Files versionsPath "\\*", "D" {
    if (A_LoopFileTimeModified > latestTime) {
        latestTime := A_LoopFileTimeModified
        latestDir := A_LoopFileFullPath
    }
}

if (latestDir = "") {
    MsgBox("Could not find Roblox installation! Is Roblox installed?", "Error", 16)
    ExitApp()
}

; Create ClientSettings folder if it does not exist
settingsDir := latestDir "\\ClientSettings"
if !DirExist(settingsDir)
    DirCreate(settingsDir)

; Write ClientAppSettings.json with the selected flags
settingsFile := settingsDir "\\ClientAppSettings.json"
if FileExist(settingsFile)
    FileDelete(settingsFile)

jsonContent := "
(
${flagsJson}
)"

FileAppend(jsonContent, settingsFile, "UTF-8")

MsgBox("Flags applied! Restart Roblox for changes to take effect.", "PS99 Optimiser", 64)
ExitApp()
`;
}

/**
 * Generate a batch (.bat) file for simple one-click application
 */
export function generateBatchScript(selectedIds: Set<string>, optimizations: Optimization[]): string {
  const flags = collectFlags(selectedIds, optimizations);
  const flagsJson = JSON.stringify(flags).replace(/"/g, '\\"');
  return `@echo off
echo PS99 FFlag Optimiser — Milamoo's Hub
echo Applying ${selectedIds.size} optimisations...
echo.
powershell -NoProfile -ExecutionPolicy Bypass -Command "
$flags = '${flagsJson}' | ConvertFrom-Json -AsHashtable;
$base = $env:LOCALAPPDATA + '\\Roblox\\Versions';
$ver = (Get-ChildItem $base -Directory | Sort LastWriteTime -Desc | Select -First 1).FullName;
$dir = $ver + '\\ClientSettings';
if (!(Test-Path $dir)) { New-Item -ItemType Directory $dir | Out-Null };
$file = $dir + '\\ClientAppSettings.json';
$existing = @{};
if (Test-Path $file) { try { $existing = Get-Content $file | ConvertFrom-Json -AsHashtable } catch {} };
foreach ($k in $flags.Keys) { $existing[$k] = $flags[$k] };
$existing | ConvertTo-Json | Set-Content $file;
Write-Host 'Done! Applied ' $flags.Count ' flags to ' $file;
"
echo.
echo Restart Roblox to apply changes!
pause
`;
}

/**
 * Master generator — pick your format
 */
export function generateScript({ format, selectedIds, optimizations }: GeneratorOptions): string {
  switch (format) {
    case 'powershell': return generatePowershellScript(selectedIds, optimizations);
    case 'json':       return generateJsonConfig(selectedIds, optimizations);
    case 'ahk':        return generateAHKScript(selectedIds, optimizations);
    case 'bat':        return generateBatchScript(selectedIds, optimizations);
    default:           return generateJsonConfig(selectedIds, optimizations);
  }
}

export function downloadScript(content: string, format: ScriptFormat, preset?: string): void {
  const ext = { powershell: 'ps1', json: 'json', ahk: 'ahk', bat: 'bat' }[format];
  const name = preset ? `ps99-optimise-${preset}.${ext}` : `ps99-optimise.${ext}`;
  const blob = new Blob([content], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = name; a.click();
  URL.revokeObjectURL(url);
}
